export const NOTICE_CATEGORY_MAP = Object.fromEntries(
  NOTICE_CATEGORIES.map(c => [c.key, c])
) as Record<string, NoticeCategory>;

export interface NoticeData {
  category: string;
  fields: Record<string, string>;
}

export function parseNotice(raw: string): NoticeData | null {
  if (!raw) return null;
  try {
    const d = JSON.parse(raw);
    if (d && d.category && d.fields) return d as NoticeData;
    return null;
  } catch {
    return null;
  }
}
