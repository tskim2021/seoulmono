  function translateUi(root) {
    if (language !== "ja" || !root) return;
    document.documentElement.lang = "ja";
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    var nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(function (node) {
      if (node.parentElement && !/^(SCRIPT|STYLE|TEXTAREA)$/i.test(node.parentElement.tagName)) {
        node.nodeValue = translateUiText(node.nodeValue || "");
      }
    });
    var elements = root.querySelectorAll ? root.querySelectorAll("[placeholder],[title],[aria-label]") : [];
    elements.forEach(function (element) {
      ["placeholder", "title", "aria-label"].forEach(function (name) {
        var value = element.getAttribute(name);
        if (value) element.setAttribute(name, translateUiText(value).trim());
      });
    });
  }

