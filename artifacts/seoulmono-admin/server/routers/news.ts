import { z } from "zod";
import { publicProcedure, protectedProcedure, adminProcedure, router } from "../_core/trpc";
import * as db from "../db";
import { TRPCError } from "@trpc/server";

export const newsRouter = router({
  // 뉴스 목록 조회 (공개)
  list: publicProcedure.input(z.object({
    categoryId: z.number().optional(),
    newsSection: z.string().optional(),
    page: z.number().optional(),
    limit: z.number().optional(),
    search: z.string().optional(),
  }).optional()).query(async ({ input }) => {
    return db.getNewsPosts({
      categoryId: input?.categoryId,
      newsSection: input?.newsSection,
      page: input?.page ?? 1,
      limit: input?.limit ?? 20,
      search: input?.search,
    });
  }),

  // 뉴스 상세 조회 (공개)
  byId: publicProcedure.input(z.object({ id: z.number() })).query(async ({ input }) => {
    const post = await db.getNewsPostById(input.id);
    if (!post) throw new TRPCError({ code: "NOT_FOUND", message: "뉴스를 찾을 수 없습니다." });
    return post;
  }),

  // 카테고리별 최신 뉴스 (홈페이지용)
  latestByCategory: publicProcedure.input(z.object({
    categoryId: z.number(),
    limit: z.number().optional(),
  })).query(async ({ input }) => {
    return db.getLatestNewsByCategory(input.categoryId, input.limit ?? 3);
  }),

  // 홈페이지용 전체 최신 뉴스
  latestForHome: publicProcedure.input(z.object({
    limit: z.number().optional(),
  }).nullish()).query(async ({ input }) => {
    return db.getLatestNewsForHome(input?.limit ?? 6);
  }),

  // ─── 관리자 기능 ───

  // 뉴스 수동 작성 (관리자)
  create: adminProcedure.input(z.object({
    title: z.string().min(1),
    content: z.string().min(1),
    categoryId: z.number(),
    newsSection: z.enum(["domestic", "international", "research"]),
    sourceUrl: z.string().optional(),
  })).mutation(async ({ ctx, input }) => {
    const postId = await db.createNewsPost({
      ...input,
      userId: ctx.user.id,
      isAutoGenerated: 0,
    });
    return { success: true, postId };
  }),

  // 뉴스 수정 (관리자)
  update: adminProcedure.input(z.object({
    id: z.number(),
    title: z.string().min(1).optional(),
    content: z.string().min(1).optional(),
    categoryId: z.number().optional(),
    newsSection: z.string().optional(),
    sourceUrl: z.string().optional(),
    isHidden: z.number().optional(),
  })).mutation(async ({ input }) => {
    const { id, ...data } = input;
    await db.updateNewsPost(id, data);
    return { success: true };
  }),

  // 뉴스 삭제 (관리자)
  delete: adminProcedure.input(z.object({ id: z.number() })).mutation(async ({ input }) => {
    await db.deleteNewsPost(input.id);
    return { success: true };
  }),

  // ─── 뉴스 자동 생성 설정 ───

  // 자동 생성 설정 조회 (관리자)
  autoSettings: adminProcedure.query(async () => {
    return db.getNewsAutoSettings();
  }),

  // 자동 생성 설정 업데이트 (관리자)
  updateAutoSetting: adminProcedure.input(z.object({
    categoryId: z.number(),
    isEnabled: z.number().optional(),
    frequency: z.string().optional(),
    generateTime: z.string().optional(),
    keywords: z.string().optional(),
    keywordsEn: z.string().optional(),
    promptTemplate: z.string().optional(),
    autoPublish: z.number().optional(),
  })).mutation(async ({ input }) => {
    const { categoryId, ...data } = input;
    await db.updateNewsAutoSetting(categoryId, data);
    return { success: true };
  }),

  // 수동 뉴스 생성 트리거 (관리자)
  generateNow: adminProcedure.input(z.object({
    categoryId: z.number(),
    newsSection: z.enum(["domestic", "international", "research"]).optional(),
  })).mutation(async ({ ctx, input }) => {
    // newsGenerator에서 호출
    const { generateNewsForCategory } = await import("../services/newsGenerator");
    const result = await generateNewsForCategory(input.categoryId, ctx.user.id, input.newsSection);
    return result;
  }),
});
