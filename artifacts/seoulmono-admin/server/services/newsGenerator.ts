import { invokeLLM } from "../_core/llm";
import * as db from "../db";
import { XMLParser } from "fast-xml-parser";

const NEWS_SECTIONS = ["domestic", "international", "research"] as const;
type NewsSection = (typeof NEWS_SECTIONS)[number];

const SECTION_LABELS: Record<NewsSection, string> = {
  domestic: "国内ニュース",
  international: "海外ニュース",
  research: "研究・論文",
};

interface RssNewsItem {
  title: string;
  link: string;
  source: string;
  pubDate: string;
}

interface GeneratedArticle {
  title: string;
  content: string;
  sourceUrl: string;
  sourceName: string;
}

// ─── Google News RSS 수집 ───────────────────────────────────────

/**
 * Google News RSS에서 키워드로 실제 뉴스를 검색합니다.
 */
async function fetchGoogleNewsRss(
  query: string,
  lang: "ko" | "en",
  maxItems: number = 10
): Promise<RssNewsItem[]> {
  const langParams =
    lang === "ko"
      ? { hl: "ja", gl: "JP", ceid: "JP:ja" }
      : { hl: "en", gl: "US", ceid: "US:en" };

  const encodedQuery = encodeURIComponent(query);
  const url = `https://news.google.com/rss/search?q=${encodedQuery}+when:7d&hl=${langParams.hl}&gl=${langParams.gl}&ceid=${langParams.ceid}`;

  try {
    const response = await fetch(url, {
      headers: {
        "User-Agent":
          "Mozilla/5.0 (compatible; NewsBot/1.0)",
      },
    });

    if (!response.ok) {
      console.error(`[NewsRSS] Failed to fetch: ${response.status} ${response.statusText}`);
      return [];
    }

    const xml = await response.text();
    const parser = new XMLParser({
      ignoreAttributes: false,
      attributeNamePrefix: "@_",
    });
    const parsed = parser.parse(xml);

    const channel = parsed?.rss?.channel;
    if (!channel?.item) return [];

    const items = Array.isArray(channel.item) ? channel.item : [channel.item];

    return items.slice(0, maxItems).map((item: any) => ({
      title: cleanHtml(typeof item.title === "string" ? item.title : String(item.title || "")),
      link: typeof item.link === "string" ? item.link : String(item.link || ""),
      source: extractSource(item),
      pubDate: typeof item.pubDate === "string" ? item.pubDate : String(item.pubDate || ""),
    }));
  } catch (err: any) {
    console.error(`[NewsRSS] Error fetching RSS for "${query}":`, err.message);
    return [];
  }
}

function cleanHtml(text: string): string {
  return text.replace(/<[^>]*>/g, "").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').trim();
}

function extractSource(item: any): string {
  if (item.source) {
    if (typeof item.source === "string") return item.source;
    if (typeof item.source === "object" && item.source["#text"]) return item.source["#text"];
  }
  return "Unknown";
}

// ─── 뉴스 생성 (실제 뉴스 기반) ────────────────────────────────

/**
 * 특정 카테고리에 대해 실제 뉴스를 수집하고 LLM으로 요약/해설합니다.
 */
export async function generateNewsForCategory(
  categoryId: number,
  userId: number,
  specificSection?: NewsSection
): Promise<{ success: boolean; generated: number; errors: string[] }> {
  const errors: string[] = [];
  let generated = 0;

  const setting = await db.getNewsAutoSettingByCategory(categoryId);
  if (!setting) {
    return { success: false, generated: 0, errors: ["カテゴリ設定が見つかりません。"] };
  }

  const sectionsToGenerate = specificSection ? [specificSection] : NEWS_SECTIONS;

  for (const section of sectionsToGenerate) {
    try {
      const article = await generateArticleFromRealNews(
        setting.keywords ?? "",
        setting.keywordsEn ?? "",
        section,
        setting.promptTemplate ?? null
      );

      if (article) {
        await db.createNewsPost({
          title: article.title,
          content: article.content,
          categoryId,
          newsSection: section,
          isAutoGenerated: 1,
          sourceUrl: article.sourceUrl,
          userId,
        });
        generated++;
      }
    } catch (err: any) {
      console.error(`[NewsGenerator] Error generating ${section} for category ${categoryId}:`, err);
      errors.push(`${SECTION_LABELS[section]} 生成に失敗しました: ${err.message}`);
    }
  }

  return { success: errors.length === 0, generated, errors };
}

/**
 * Google News RSS에서 실제 뉴스를 수집한 뒤 LLM으로 요약/해설합니다.
 */
async function generateArticleFromRealNews(
  keywords: string,
  keywordsEn: string,
  section: NewsSection,
  customPrompt: string | null
): Promise<GeneratedArticle | null> {
  // 1) 섹션에 따라 검색어와 언어 결정
  const { query, lang } = buildSearchQuery(keywords, keywordsEn, section);

  // 2) Google News RSS에서 실제 뉴스 수집
  const newsItems = await fetchGoogleNewsRss(query, lang, 8);

  if (newsItems.length === 0) {
    console.warn(`[NewsGenerator] No news found for query "${query}" (${section})`);
    return null;
  }

  // 3) 수집된 뉴스 목록을 LLM에 전달하여 요약/해설 작성
  const newsListText = newsItems
    .map(
      (item, idx) =>
        `${idx + 1}. タイトル: ${item.title}\n   出典: ${item.source}\n   発行日: ${item.pubDate}\n   リンク: ${item.link}`
    )
    .join("\n\n");

  const today = new Date().toISOString().split("T")[0];
  const sectionGuide = getSectionPrompt(section);

  const systemPrompt =
    customPrompt ||
    `あなたは健康・医薬品分野の専門ニュースエディターです。
実際のニュース記事を分析し、読者に役立つ要約・解説記事を作成します。
記事は日本語で、専門的でありながら一般の読者にも分かりやすく書きます。
必ず実際のニュースの出典を明記し、元記事の要点を正確に伝えます。
誇張した表現は避け、客観的な視点で書きます。`;

  const userPrompt = `今日の日付: ${today}

以下は「${keywords}」に関する最新の${SECTION_LABELS[section]}一覧です。
これらの実際のニュースをもとに、総合的な要約・解説記事を1件作成してください。

=== 収集した実際のニュース ===
${newsListText}
========================

${sectionGuide}

作成ルール:
1. 最も重要で新しいニュースを1〜3件選び、総合記事を作成してください。
2. 必ず元記事の出典（報道機関名）を本文に明記してください（例: 「朝日新聞によると…」「共同通信の報道によれば…」）
3. 記事の末尾に「出典: [報道機関名]」の形式で参照した出典を列挙してください。
4. 元記事の要点を正確に伝えつつ、読者が理解しやすいよう解説を加えてください。

次のJSON形式で回答してください:
{
  "title": "要約記事のタイトル（要点を表す簡潔なタイトル）",
  "content": "要約・解説記事の本文（Markdown形式、500文字以上、小見出し・段落分けを含む、出典を明記）",
  "mainSourceIndex": 最も重要なニュースの番号（1から始まる数字）
}`;

  const response = await invokeLLM({
    messages: [
      { role: "system", content: systemPrompt },
      { role: "user", content: userPrompt },
    ],
    response_format: {
      type: "json_schema",
      json_schema: {
        name: "news_summary_article",
        strict: true,
        schema: {
          type: "object",
          properties: {
            title: { type: "string", description: "要約記事のタイトル" },
            content: { type: "string", description: "要約・解説記事の本文（Markdown）" },
            mainSourceIndex: { type: "integer", description: "主要ニュースの番号（1から）" },
          },
          required: ["title", "content", "mainSourceIndex"],
          additionalProperties: false,
        },
      },
    },
  });

  const responseContent = response.choices[0]?.message?.content;
  if (!responseContent || typeof responseContent !== "string") return null;

  try {
    const parsed = JSON.parse(responseContent) as {
      title: string;
      content: string;
      mainSourceIndex: number;
    };
    if (!parsed.title || !parsed.content) return null;

    // 핵심 뉴스의 원문 링크를 sourceUrl로 저장
    const mainIdx = Math.max(0, Math.min((parsed.mainSourceIndex || 1) - 1, newsItems.length - 1));
    const mainSource = newsItems[mainIdx];

    return {
      title: parsed.title,
      content: parsed.content,
      sourceUrl: mainSource?.link || newsItems[0]?.link || "",
      sourceName: mainSource?.source || newsItems[0]?.source || "",
    };
  } catch {
    console.error("[NewsGenerator] Failed to parse LLM response:", responseContent);
    return null;
  }
}

/**
 * 섹션별 검색어와 언어를 결정합니다.
 */
function buildSearchQuery(
  keywords: string,
  keywordsEn: string,
  section: NewsSection
): { query: string; lang: "ko" | "en" } {
  const kwList = keywords
    .split(",")
    .map((k) => k.trim())
    .filter(Boolean);
  const kwEnList = keywordsEn
    .split(",")
    .map((k) => k.trim())
    .filter(Boolean);

  switch (section) {
    case "domestic": {
      // 국내 뉴스: 한국어 키워드로 한국 뉴스 검색
      const q = kwList.length > 0 ? kwList.slice(0, 3).join(" OR ") : "健康";
      return { query: q, lang: "ko" };
    }
    case "international": {
      // 해외 뉴스: 영어 키워드로 영어 뉴스 검색
      const q = kwEnList.length > 0 ? kwEnList.slice(0, 3).join(" OR ") : "health";
      return { query: q, lang: "en" };
    }
    case "research": {
      // 연구/논문: 영어 키워드 + "study OR research OR clinical trial"
      const base = kwEnList.length > 0 ? kwEnList[0] : "health";
      return { query: `${base} study OR research OR clinical trial`, lang: "en" };
    }
  }
}

function getSectionPrompt(section: NewsSection): string {
  switch (section) {
    case "domestic":
      return `[国内ニュース要約ガイド]
- 国内の関連ニュース、政策の変化、市場動向を中心に要約します。
- 厚生労働省、PMDAなど国内機関の発表があれば強調します。
- 日本の消費者に実際に役立つ情報を提供します。
- 元記事の要点を正確に伝えます。`;

    case "international":
      return `[海外ニュース要約ガイド]
- FDA、EMAなど海外規制当局の最新の承認・規制ニュースを中心に要約します。
- グローバル製薬企業の新薬開発、臨床試験結果を含めます。
- 海外ニュースのため、日本語に翻訳して解説します。
- 日本市場への影響があれば分析を加えます。`;

    case "research":
      return `[研究・論文要約ガイド]
- 最新の学術研究の結果を一般の方にも分かるよう解説します。
- 研究の主要な発見、方法論、限界点を明確に説明します。
- 臨床試験の結果は段階（Phase 1/2/3）を明記します。
- 海外の研究の場合は日本語に翻訳して解説します。
- 研究の実生活への応用可能性と今後の展望を含めます。`;
  }
}

/**
 * 모든 활성화된 카테고리에 대해 뉴스를 자동 생성합니다.
 * 스케줄러에서 호출됩니다.
 */
export async function generateAllEnabledNews(systemUserId: number): Promise<{
  totalGenerated: number;
  categoryResults: Array<{ categoryId: number; generated: number; errors: string[] }>;
}> {
  const settings = await db.getEnabledNewsAutoSettings();
  let totalGenerated = 0;
  const categoryResults: Array<{ categoryId: number; generated: number; errors: string[] }> = [];

  for (const setting of settings) {
    const result = await generateNewsForCategory(setting.categoryId, systemUserId);
    totalGenerated += result.generated;
    categoryResults.push({
      categoryId: setting.categoryId,
      generated: result.generated,
      errors: result.errors,
    });
  }

  console.log(`[NewsGenerator] Auto generation complete: ${totalGenerated} articles generated`);
  return { totalGenerated, categoryResults };
}
