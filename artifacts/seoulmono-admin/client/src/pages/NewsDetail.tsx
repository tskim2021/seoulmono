import Layout from "@/components/Layout";
import { trpc } from "@/lib/trpc";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent } from "@/components/ui/card";
import { Skeleton } from "@/components/ui/skeleton";
import { Textarea } from "@/components/ui/textarea";
import { ArrowLeft, Eye, MessageCircle, Calendar, Newspaper, Globe, FlaskConical, ExternalLink, ThumbsUp, Send } from "lucide-react";
import { Link, useParams, useLocation } from "wouter";
import { useState } from "react";
import { useAuth } from "@/_core/hooks/useAuth";
import { getLoginUrl } from "@/const";
import { useSEO } from "@/hooks/useSEO";
import { toast } from "sonner";
import { Streamdown } from "streamdown";

const SECTION_LABELS: Record<string, { label: string; icon: any; color: string }> = {
  domestic: { label: "国内ニュース", icon: Newspaper, color: "bg-blue-100 text-blue-700" },
  international: { label: "海外ニュース", icon: Globe, color: "bg-emerald-100 text-emerald-700" },
  research: { label: "研究・論文", icon: FlaskConical, color: "bg-purple-100 text-purple-700" },
};

export default function NewsDetail() {
  const { id } = useParams<{ id: string }>();
  const [, setLocation] = useLocation();
  const { user } = useAuth();
  const [commentText, setCommentText] = useState("");

  const newsId = Number(id);
  const { data: news, isLoading, error } = trpc.news.byId.useQuery(
    { id: newsId },
    { enabled: !isNaN(newsId), retry: false }
  );

  const { data: categoriesData } = trpc.category.list.useQuery();
  const { data: commentsData, refetch: refetchComments } = trpc.community.comments.useQuery(
    { postId: newsId },
    { enabled: !isNaN(newsId) }
  );

  const createComment = trpc.community.createComment.useMutation({
    onSuccess: () => {
      setCommentText("");
      refetchComments();
      toast.success("コメントを投稿しました。");
    },
    onError: (err) => {
      toast.error(err.message);
    },
  });

  // 같은 카테고리 관련 뉴스
  const { data: relatedNews } = trpc.news.latestByCategory.useQuery(
    { categoryId: news?.categoryId ?? 0, limit: 4 },
    { enabled: !!news?.categoryId }
  );

  useSEO({
    title: news ? `${news.title} - 健康ニュース` : "健康ニュース",
    description: news ? news.content.slice(0, 160) : undefined,
  });

  const formatDate = (date: string | Date) => {
    return new Date(date).toLocaleDateString("ja-JP", {
      year: "numeric",
      month: "long",
      day: "numeric",
      hour: "2-digit",
      minute: "2-digit",
    });
  };

  const handleSubmitComment = () => {
    if (!commentText.trim()) return;
    createComment.mutate({ postId: newsId, content: commentText.trim() });
  };

  if (isLoading) {
    return (
      <Layout>
        <div className="container py-8 max-w-4xl mx-auto">
          <Skeleton className="h-8 w-64 mb-4" />
          <Skeleton className="h-6 w-full mb-2" />
          <Skeleton className="h-6 w-3/4 mb-6" />
          <Skeleton className="h-96 w-full" />
        </div>
      </Layout>
    );
  }

  if (error || !news) {
    return (
      <Layout>
        <div className="container py-16 text-center">
          <Newspaper className="w-16 h-16 text-muted-foreground/30 mx-auto mb-4" />
          <h2 className="text-xl font-semibold mb-2">ニュースが見つかりません</h2>
          <p className="text-muted-foreground mb-6">削除されたか、存在しないニュースです。</p>
          <Button asChild>
            <Link href="/news">ニュース一覧へ</Link>
          </Button>
        </div>
      </Layout>
    );
  }

  const sectionInfo = news.newsSection ? SECTION_LABELS[news.newsSection] : null;
  const categoryName = categoriesData?.find((c: any) => c.id === news.categoryId)?.name;
  const filteredRelated = relatedNews?.filter((r: any) => r.id !== news.id).slice(0, 3) ?? [];

  return (
    <Layout>
      <div className="bg-gradient-to-br from-blue-50/50 via-white to-emerald-50/50 min-h-screen">
        <div className="container py-6 max-w-4xl mx-auto">
          {/* 뒤로가기 */}
          <Button variant="ghost" size="sm" className="mb-4 -ml-2" onClick={() => setLocation("/news")}>
            <ArrowLeft className="w-4 h-4 mr-1" /> ニュース一覧
          </Button>

          {/* 기사 헤더 */}
          <article>
            <div className="flex flex-wrap items-center gap-2 mb-3">
              {sectionInfo && (
                <Badge className={`${sectionInfo.color} text-xs`}>
                  {sectionInfo.label}
                </Badge>
              )}
              {categoryName && (
                <Badge variant="outline" className="text-xs">{categoryName}</Badge>
              )}
              {news.isAutoGenerated === 1 && (
                <Badge variant="outline" className="text-xs text-muted-foreground">AI要約 · 実ニュース基準</Badge>
              )}
            </div>

            <h1 className="text-2xl md:text-3xl font-bold tracking-tight mb-4 leading-tight">
              {news.title}
            </h1>

            <div className="flex flex-wrap items-center gap-4 text-sm text-muted-foreground mb-6 pb-6 border-b">
              <span className="flex items-center gap-1">
                <Calendar className="w-4 h-4" />
                {formatDate(news.createdAt)}
              </span>
              <span className="flex items-center gap-1">
                <Eye className="w-4 h-4" />
                閲覧 {news.viewCount}
              </span>
              <span className="flex items-center gap-1">
                <MessageCircle className="w-4 h-4" />
                コメント {news.commentCount}
              </span>
              {news.sourceUrl && (
                <a
                  href={news.sourceUrl}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="flex items-center gap-1 text-primary hover:underline"
                >
                  <ExternalLink className="w-4 h-4" />
                  元記事を見る
                </a>
              )}
            </div>

            {/* 원문 출처 배너 */}
            {news.sourceUrl && (
              <div className="bg-blue-50 border border-blue-200 rounded-lg p-4 mb-6 flex items-start gap-3">
                <ExternalLink className="w-5 h-5 text-blue-600 shrink-0 mt-0.5" />
                <div className="flex-1 min-w-0">
                  <p className="text-sm font-medium text-blue-900 mb-1">この記事は、実際のニュースをもとにAIが要約・解説したコンテンツです。</p>
                  <a
                    href={news.sourceUrl}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="text-sm text-blue-700 hover:text-blue-900 underline break-all"
                  >
                    元記事を見る →
                  </a>
                </div>
              </div>
            )}

            {/* 기사 본문 */}
            <div className="prose prose-sm md:prose-base max-w-none mb-8 [&_h2]:text-xl [&_h2]:font-bold [&_h2]:mt-8 [&_h2]:mb-3 [&_h3]:text-lg [&_h3]:font-semibold [&_h3]:mt-6 [&_h3]:mb-2 [&_p]:leading-relaxed [&_p]:mb-4 [&_ul]:mb-4 [&_ol]:mb-4 [&_li]:mb-1 [&_blockquote]:border-l-4 [&_blockquote]:border-primary/30 [&_blockquote]:pl-4 [&_blockquote]:italic [&_blockquote]:text-muted-foreground">
              <Streamdown>{news.content}</Streamdown>
            </div>
          </article>

          {/* 댓글 섹션 */}
          <section className="mt-8 pt-8 border-t">
            <h2 className="text-lg font-semibold mb-4 flex items-center gap-2">
              <MessageCircle className="w-5 h-5" />
              コメント {commentsData?.length ? `(${commentsData.length})` : ""}
            </h2>

            {/* 댓글 작성 */}
            {user ? (
              <div className="mb-6">
                <Textarea
                  placeholder="ニュースについてのご意見をお寄せください..."
                  value={commentText}
                  onChange={(e) => setCommentText(e.target.value)}
                  rows={3}
                  className="mb-2"
                />
                <div className="flex justify-end">
                  <Button
                    size="sm"
                    onClick={handleSubmitComment}
                    disabled={!commentText.trim() || createComment.isPending}
                  >
                    <Send className="w-4 h-4 mr-1" />
                    {createComment.isPending ? "投稿中..." : "コメントを投稿"}
                  </Button>
                </div>
              </div>
            ) : (
              <Card className="mb-6">
                <CardContent className="p-4 text-center">
                  <p className="text-sm text-muted-foreground mb-2">コメントを投稿するにはログインが必要です。</p>
                  <Button size="sm" asChild>
                    <a href={getLoginUrl()}>ログイン</a>
                  </Button>
                </CardContent>
              </Card>
            )}

            {/* 댓글 목록 */}
            {commentsData && commentsData.length > 0 ? (
              <div className="space-y-4">
                {commentsData.map((comment: any) => (
                  <div key={comment.id} className="flex gap-3">
                    <div className="w-8 h-8 rounded-full bg-muted flex items-center justify-center shrink-0 text-xs font-medium">
                      {comment.userName?.charAt(0) || "?"}
                    </div>
                    <div className="flex-1 min-w-0">
                      <div className="flex items-center gap-2 mb-1">
                        <span className="text-sm font-medium">{comment.userName || "匿名"}</span>
                        {comment.isAdmin === 1 && (
                          <Badge variant="secondary" className="text-xs">管理者</Badge>
                        )}
                        <span className="text-xs text-muted-foreground">
                          {formatDate(comment.createdAt)}
                        </span>
                      </div>
                      <p className="text-sm text-foreground/80 whitespace-pre-wrap">{comment.content}</p>
                    </div>
                  </div>
                ))}
              </div>
            ) : (
              <p className="text-sm text-muted-foreground text-center py-8">
                まだコメントがありません。最初のコメントを投稿してみましょう！
              </p>
            )}
          </section>

          {/* 관련 뉴스 */}
          {filteredRelated.length > 0 && (
            <section className="mt-10 pt-8 border-t">
              <h2 className="text-lg font-semibold mb-4">関連ニュース</h2>
              <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
                {filteredRelated.map((related: any) => (
                  <Link key={related.id} href={`/news/${related.id}`}>
                    <Card className="hover:shadow-md transition-shadow cursor-pointer h-full">
                      <CardContent className="p-4">
                        {related.newsSection && (
                          <Badge variant="secondary" className={`text-xs mb-2 ${SECTION_LABELS[related.newsSection]?.color || ""}`}>
                            {SECTION_LABELS[related.newsSection]?.label || related.newsSection}
                          </Badge>
                        )}
                        <h3 className="font-medium text-sm leading-snug line-clamp-2 mb-2">{related.title}</h3>
                        <span className="text-xs text-muted-foreground">{formatDate(related.createdAt)}</span>
                      </CardContent>
                    </Card>
                  </Link>
                ))}
              </div>
            </section>
          )}
        </div>
      </div>
    </Layout>
  );
}
